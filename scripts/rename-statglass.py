#!/usr/bin/env python3
"""One-time tracked-file rename. Default: dry run; --apply: write; --check: verify.

Exceptions preserve signed evidence, generated files awaiting regeneration, and
historical records. The live release key backup remains at its original path.
Only tracked files are considered; untracked and ignored files are never edited.
"""

import argparse
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(subprocess.check_output(['git', 'rev-parse', '--show-toplevel'], text=True).strip())
os.chdir(ROOT)
MAPPINGS = (('kelvo', 'statglass'), ('Kelvo', 'StatGlass'), ('KELVO', 'STATGLASS'))
# These are immutable evidence or are regenerated by their owning tools.
PROTECTED = {
    'AGENTS.md', 'Cargo.lock', 'bun.lock', 'plan/rename-statglass.md',
    'scripts/rename-statglass.py', 'scripts/test-rename-statglass.py',
    'src-tauri/tests/fixtures/update-payload',
    'src-tauri/tests/fixtures/update-payload.sig',
    'crates/kelvo-update/tests/fixtures/release.json',
    'crates/kelvo-update/tests/fixtures/release.json.sig',
    'CHANGELOG.md', 'plan/PROGRESS.md', 'plan/decisions.md',
    'plan/agent-ops-post-mortem-2026-10-25.md',
    'plan/architecture-refactor-review.md', 'plan/history-remote-landing.md',
    'plan/tray-performance.md', 'plan/ux-history-execution.md',
    'plan/ux-history-feasibility-1000.jsonl', 'plan/ux-native-execution.md',
    'plan/ux-timeline-execution.md',
}
PROTECTED_PREFIXES = ('.agents/rules/', 'src/core/generated/')
# The catalog fixture is re-signed under its new release-channel basename.
CATALOG_FIXTURES = {
    'crates/kelvo-update/tests/fixtures/release.json':
        'crates/statglass-update/tests/fixtures/statglass-release.json',
    'crates/kelvo-update/tests/fixtures/release.json.sig':
        'crates/statglass-update/tests/fixtures/statglass-release.json.sig',
}
# The private key backup is intentionally not moved; both spellings are in use.
LITERALS = (
    '~/.config/kelvo/release/updater.key',
    '$HOME/.config/kelvo/release/updater.key',
)
UNEXPECTED = re.compile(r'kelvo', re.IGNORECASE)


def rename(value):
    for old, new in MAPPINGS:
        value = value.replace(old, new)
    return value


def protected(path):
    return (path in PROTECTED or path in {rename(item) for item in PROTECTED}
            or path.startswith(PROTECTED_PREFIXES))


def transform(content, path):
    # Retain exact literal spans without relying on placeholder characters that
    # might already occur in a source file.
    literals_to_preserve = LITERALS
    if path in ('crates/kelvo-proto/tests/pre_d116/mod.rs',
                'crates/statglass-proto/tests/pre_d116/mod.rs'):
        # These paths identify files in a historical commit.
        literals_to_preserve += ('crates/kelvo-proto/src/message.rs',
                                 'crates/kelvo-schema/src/{host,caps,catalog,compat}.rs')
        # Undo the initial mechanical rewrite of these historical git-show paths.
        content = content.replace('crates/statglass-proto/src/message.rs',
                                  'crates/kelvo-proto/src/message.rs')
        content = content.replace('crates/statglass-schema/src/{host,caps,catalog,compat}.rs',
                                  'crates/kelvo-schema/src/{host,caps,catalog,compat}.rs')
    for name in ('caps', 'catalog', 'compat', 'host'):
        if path in (f'crates/kelvo-proto/tests/pre_d116/{name}.rs',
                    f'crates/statglass-proto/tests/pre_d116/{name}.rs'):
            old = f'kelvo-schema/src/{name}.rs'
            literals_to_preserve += (old,)
            content = content.replace(f'statglass-schema/src/{name}.rs', old)
    if path in ('crates/kelvo-update/src/tests.rs', 'crates/statglass-update/src/tests.rs'):
        # The updater must reject artifacts from the retired repository.
        literals_to_preserve += ('https://github.com/steamfield/kelvo/releases/download/v9.0.0/a',)
    pattern = re.compile('|'.join(re.escape(value) for value in literals_to_preserve))
    pieces = pattern.split(content)
    literals = pattern.findall(content)
    return ''.join(rename(piece) + (literals[i] if i < len(literals) else '')
                   for i, piece in enumerate(pieces))


def git(*args):
    return subprocess.check_output(['git', *args]).decode('utf-8', 'surrogateescape')


def symlink_ancestor(path):
    for parent in Path(path).parents:
        if parent == Path('.'):
            continue
        if parent.is_symlink():
            return str(parent)
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--apply', action='store_true')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args()
    tracked = sorted(git('ls-files', '-z').split('\0')[:-1])
    dirty = set(git('diff', '--name-only', '-z', 'HEAD', '--').split('\0'))
    sources = set(tracked)
    moves, edits, problems = [], [], []
    destinations = {}
    for original in tracked:
        destination = rename(original)
        if destination in destinations:
            problems.append(f'collision: {original} and {destinations[destination]} -> {destination}')
        destinations[destination] = original
        for path in (original, destination):
            ancestor = symlink_ancestor(path)
            if ancestor:
                problems.append(f'symlink ancestor for {path}: {ancestor}')
    for destination in destinations:
        for parent in Path(destination).parents:
            if parent == Path('.'):
                continue
            if str(parent) in destinations:
                problems.append(f'destination parent is also a file: {parent} for {destination}')
            elif os.path.lexists(parent) and not parent.is_dir():
                problems.append(f'destination parent is not a directory: {parent} for {destination}')
    if problems:
        for problem in sorted(set(problems)):
            print(f'ERROR {problem}', file=sys.stderr)
        return 2
    for original in tracked:
        destination = rename(original)
        # Protected bytes may move with a renamed parent directory.
        source = Path(original)
        if original in CATALOG_FIXTURES and not os.path.lexists(source):
            replacement = Path(CATALOG_FIXTURES[original])
            ancestor = symlink_ancestor(replacement)
            if ancestor:
                problems.append(f'symlink ancestor for {replacement}: {ancestor}')
                continue
            if replacement.exists() and not replacement.is_symlink():
                source = replacement
        if not source.exists() and not source.is_symlink() and Path(destination).exists():
            source = Path(destination)  # already applied, before staging
        if not source.exists() and not source.is_symlink():
            problems.append(f'missing tracked file: {original}')
            continue
        if source.is_symlink():
            # Never dereference or alter symlinks, including their target text.
            if str(source) != destination:
                problems.append(f'symlink needs manual rename: {original}')
            continue
        if destination != original and str(source) == original:
            if os.path.lexists(destination) and destination not in sources:
                problems.append(f'destination exists: {destination}')
            moves.append((original, destination))
        if not protected(original):
            data = source.read_bytes()
            try:
                content = data.decode('utf-8') if b'\0' not in data else None
            except UnicodeDecodeError:
                content = None
            if content is not None:
                for match in UNEXPECTED.finditer(content):
                    if match.group() not in ('kelvo', 'Kelvo', 'KELVO'):
                        problems.append(f'unexpected casing in {original}: {match.group()}')
                changed = transform(content, original).encode('utf-8')
                if changed != data:
                    edits.append((str(source), changed))
        for match in UNEXPECTED.finditer(original):
            if match.group() not in ('kelvo', 'Kelvo', 'KELVO'):
                problems.append(f'unexpected casing in path {original}: {match.group()}')
    if args.apply:
        affected = {old for old, _ in moves} | {path for path, _ in edits}
        for path in sorted(dirty & affected):
            problems.append(f'affected tracked file has uncommitted changes: {path}')
    for problem in sorted(set(problems)):
        print(f'ERROR {problem}', file=sys.stderr)
    if problems:
        return 2
    for path, _ in edits:
        print(f'EDIT {path}')
    for old, new in moves:
        print(f'MOVE {old} -> {new}')
    print(f'{len(edits)} content edits; {len(moves)} file moves')
    if args.check:
        return int(bool(edits or moves))
    if args.apply:
        for path, data in edits:
            Path(path).write_bytes(data)
        # Move files deepest-first. Creating new parents avoids carrying ignored or
        # untracked files along with a renamed tracked directory.
        for old, new in sorted(moves, key=lambda pair: (-pair[0].count('/'), pair[0])):
            Path(new).parent.mkdir(parents=True, exist_ok=True)
            os.rename(old, new)
        for parent in sorted({p for old, _ in moves for p in Path(old).parents if str(p) != '.'},
                             key=lambda p: (-len(p.parts), str(p))):
            try:
                parent.rmdir()
            except OSError:
                pass  # A directory containing untracked or ignored files stays put.
    return 0


if __name__ == '__main__':
    sys.exit(main())
